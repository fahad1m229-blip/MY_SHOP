let seedPromise = null;

async function ensureInitialCatalogSeeded(db) {
  if (!db) return;
  if (seedPromise) return seedPromise;

  seedPromise = (async () => {
    try {
      const metaRef = db.collection("site_config").doc("catalog_seed_meta");
      const metaSnap = await metaRef.get();
      if (metaSnap.exists && metaSnap.data()?.seeded === true) {
        return;
      }

      const [prodSnap, catSnap] = await Promise.all([
        db.collection("catalog_products").limit(1).get(),
        db.collection("catalog_categories").limit(1).get(),
      ]);

      // Only seed when the database has no categories & products yet
      if (!prodSnap.empty || !catSnap.empty) {
        await metaRef.set(
          { seeded: true, note: "Existing catalog preserved", updatedAt: admin.firestore.FieldValue.serverTimestamp() },
          { merge: true }
        );
        return;
      }

      const batch = db.batch();
      const now = admin.firestore.FieldValue.serverTimestamp();

      for (const c of DEFAULT_CATEGORIES) {
        batch.set(db.collection("catalog_categories").doc(c.id), { ...c, updatedAt: now }, { merge: true });
      }
      for (const b of DEFAULT_BRANDS) {
        batch.set(db.collection("catalog_brands").doc(b.id), { ...b, updatedAt: now }, { merge: true });
      }
      for (const coupon of DEFAULT_COUPONS) {
        batch.set(db.collection("catalog_coupons").doc(coupon.code), { ...coupon, updatedAt: now }, { merge: true });
      }
      for (const prod of DEFAULT_PRODUCTS) {
        batch.set(
          db.collection("catalog_products").doc(prod.id),
          { ...prod, createdAt: now, updatedAt: now },
          { merge: true }
        );
      }

      // Ensure baseline CMS / Fun Zone / AI / Social Support settings exist without overwriting existing edits
      const [siteSnap, socialSnap, annSnap, fzSnap, aiSnap] = await Promise.all([
        db.collection("site_config").doc("main").get(),
        db.collection("social_support_settings").doc("main").get(),
        db.collection("announcement_settings").doc("main").get(),
        db.collection("fun_zone_config").doc("rules").get(),
        db.collection("ai_settings").doc("main").get(),
      ]);

      if (!siteSnap.exists) batch.set(db.collection("site_config").doc("main"), { ...defaultSiteConfig(), updatedAt: now });
      if (!socialSnap.exists) batch.set(db.collection("social_support_settings").doc("main"), { ...defaultSocialSupportSettings(), updatedAt: now });
      if (!annSnap.exists) batch.set(db.collection("announcement_settings").doc("main"), { ...defaultAnnouncementSettings(), updatedAt: now });
      if (!fzSnap.exists) batch.set(db.collection("fun_zone_config").doc("rules"), { ...defaultFunZoneConfig(), updatedAt: now });
      if (!aiSnap.exists) batch.set(db.collection("ai_settings").doc("main"), { ...defaultAiSettings(), updatedAt: now });

      batch.set(metaRef, { seeded: true, version: 1, seededAt: now }, { merge: true });
      await batch.commit();
    } catch (err) {
      console.warn("[Seed] Initial catalog seed skipped:", err.message);
    } finally {
      seedPromise = null;
    }
  })();

  return seedPromise;
}

